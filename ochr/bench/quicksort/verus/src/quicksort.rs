// and compares it with `expected`.

struct Tally {
    passed: u64,
    failed: u64,
}

fn case(t: &mut Tally, name: &str, input: &[u64], expected: &[u64]) {
    let mut a = input.to_vec();
    quicksort(&mut a);
    if a == expected {
        t.passed += 1;
    } else {
        t.failed += 1;
        println!("FAIL {name}: got {a:?}, expected {expected:?}");
    }
}

